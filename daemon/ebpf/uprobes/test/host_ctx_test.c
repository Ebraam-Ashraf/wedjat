/* ============================================================
 * ASSERTION MACROS
 *
 * Lightweight — no framework needed.  Each macro prints a human-readable
 * failure message and returns 1 from the enclosing function on failure.
 * ============================================================ */

/* Assert a boolean condition is true. */
#define ASSERT_TRUE(cond, msg)                                          \
    do {                                                                \
        if (!(cond)) {                                                  \
            fprintf(stderr, "FAIL [%s:%d]: %s\n",                      \
                    __FILE__, __LINE__, (msg));                         \
            return 1;                                                   \
        }                                                               \
    } while (0)

/* Assert two integer values are equal. */
#define ASSERT_EQ(actual, expected, msg)                                \
    do {                                                                \
        if ((actual) != (expected)) {                                   \
            fprintf(stderr, "FAIL [%s:%d]: %s (got %ld, want %ld)\n",  \
                    __FILE__, __LINE__, (msg),                          \
                    (long)(actual), (long)(expected));                  \
            return 1;                                                   \
        }                                                               \
    } while (0)

/* Assert actual >= expected. */
#define ASSERT_GE(actual, expected, msg)                                \
    do {                                                                \
        if ((actual) < (expected)) {                                    \
            fprintf(stderr, "FAIL [%s:%d]: %s (got %ld, want >= %ld)\n",\
                    __FILE__, __LINE__, (msg),                          \
                    (long)(actual), (long)(expected));                  \
            return 1;                                                   \
        }                                                               \
    } while (0)

