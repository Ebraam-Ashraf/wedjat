/*
 * daemon/ebpf/uprobes/test/host_ctx_test.c
 *
 * Integration test for host_ctx.bpf.c — the cuLaunchKernel uprobe.
 *
 * WHAT THIS FILE DOES:
 *   1. Loads host_ctx.bpf.o into the kernel (Level 1+2: compile + verifier).
 *   2. Attaches the probe to cuLaunchKernel in libcuda.so (Level 3: attach).
 *   3. Forks and execs a CUDA fixture binary (k1) as a child process.
 *      The fixture calls cuLaunchKernel in a loop — that's the trigger.
 *   4. Polls the ring buffer while the child runs, collecting events.
 *   5. Filters events down to the child's PID so other CUDA processes
 *      on the same machine don't pollute the assertions.
 *   6. After the child exits, drains any remaining events, then asserts:
 *        - at least WEDJAT_ITERS events arrived (one per launch)
 *        - every event has a non-zero timestamp
 *        - every event has a non-empty comm string
 *        - every event has grid_x > 0 and a valid block_x (Level 4).
 *
 * HOW TO BUILD (once host_ctx.skel.h exists):
 *   See test/Makefile — the skeleton is generated by bpftool, then this
 *   file is compiled with clang -lbpf.
 *
 * HOW TO RUN:
 *   sudo ./bin/host_ctx_test k1
 *   sudo ./bin/host_ctx_test k2
 *
 *   Requires root (CAP_BPF + CAP_PERFMON) and a real GPU.
 *   k1/k2 must already be built: make -C ../../../../kernels_to_trace build
 *
 * CURRENT STATE:
 *   The BPF skeleton (host_ctx.skel.h) does not exist yet — it is generated
 *   from host_ctx.bpf.o once host_ctx.bpf.c compiles cleanly.  The real
 *   loader/attach/ringbuf blocks are inside TODO comments below so the shape
 *   is visible.  The fork/exec/waitpid skeleton is fully real and compiles
 *   today without libbpf.
 */

